def main():
    api = check_api(model="qwen")
    print("api:", api)
    if not api.get("ok"):
        print("Qwen недоступен")
        sys.exit(1)

    parts = ["# Материалы для архитектурного разбора OstraI18n\n"]
    for f in DOC_FILES:
        parts.append(section_md(f, f))
    for f in PLUGIN_FILES:
        parts.append(section(f, f))
    for f in DECOMPILED_FILES:
        parts.append(section(f, f))

    user_content = "".join(parts)
    print("user_content chars:", len(user_content))

    model = sys.argv[1] if len(sys.argv) > 1 else "qwen3.8-max"
    result = chat_text(SYS_PROMPT, user_content, model=model, max_tokens=16000)

    io.open(OUT, "w", encoding="utf-8").write(result)
    print("written:", OUT, "chars:", len(result))


if __name__ == "__main__":
    main()
